export function buildCompleteMarketUniverse(): StockData[] {
  // 1. Compute weighted scores for each stock in the 100 universe
  const scores = sp500TopPerformers.map((s) => calculateRSWeightedScore(s.q1, s.q2, s.q3, s.q4));
  // 2. Rank percentiles across the 100 stocks (1-99)
  const percentiles = calculatePercentileRanks(scores);

  return sp500TopPerformers.map((raw, index) => {
    const rsWeightedScore = scores[index];
    const rsRating = percentiles[index];
    const annualGainPct = ((raw.currentPrice - raw.basePrice1YAgo) / raw.basePrice1YAgo) * 100;

    const history = generateStockHistory(
      raw.basePrice1YAgo,
      annualGainPct,
      raw.volatility,
      raw.rsLineNewHighBeforePrice,
      raw.currentPrice
    );

    const last = history[history.length - 1];
    const sma50 = last.sma50 || raw.currentPrice * 0.94;
    const sma200 = last.sma200 || raw.currentPrice * 0.82;
    const sma150 = (sma50 + sma200) / 2;
    const sma200SlopePositive = raw.rsLineSlopePositive && raw.currentPrice > sma200;

    const quarterly: QuarterlyPerformance = {
      q1: raw.q1,
      q2: raw.q2,
      q3: raw.q3,
      q4: raw.q4,
      weightedScore: rsWeightedScore,
    };

    const criteriaEvaluation = evaluateRSCriteria({
      currentPrice: raw.currentPrice,
      high52W: raw.high52W,
      low52W: raw.low52W,
      sma50,
      sma150,
      sma200,
      sma200SlopePositive,
      rsRating,
      rsLineSlopePositive: raw.rsLineSlopePositive,
      rsLineAbove50SMA: raw.rsLineAbove50SMA,
      rsLineNewHighBeforePrice: raw.rsLineNewHighBeforePrice,
      spyCorrelationInCorrection: raw.spyCorrelationInCorrection,
      upDownVolumeRatio: raw.upDownVolumeRatio,
    });

    return {
      symbol: raw.symbol,
      name: raw.name,
      sector: raw.sector,
      industry: raw.industry,
      currentPrice: raw.currentPrice,
      change1D: Number((raw.currentPrice * (raw.change1DPercent / 100)).toFixed(2)),
      change1DPercent: raw.change1DPercent,
      change1YPercent: Number(annualGainPct.toFixed(1)),
      high52W: raw.high52W,
      low52W: raw.low52W,
      sma50: Number(sma50.toFixed(2)),
      sma150: Number(sma150.toFixed(2)),
      sma200: Number(sma200.toFixed(2)),
      sma200SlopePositive,
      rsRating,
      previousRsRating: Math.max(1, rsRating - (raw.q4 > 45 ? 3 : -1)),
      rsWeightedScore,
      quarterly,
      rsLineNewHighBeforePrice: raw.rsLineNewHighBeforePrice,
      rsLineSlopePositive: raw.rsLineSlopePositive,
      rsLineAbove50SMA: raw.rsLineAbove50SMA,
      spyCorrelationInCorrection: raw.spyCorrelationInCorrection,
      volumeAverage50D: 2_800_000,
      recentVolume: Math.floor(2_800_000 * (raw.upDownVolumeRatio > 1.2 ? 1.35 : 0.85)),
      upDownVolumeRatio: raw.upDownVolumeRatio,
      criteriaScore: criteriaEvaluation.criteriaScore,
      criteriaResults: criteriaEvaluation.criteriaResults,
      verdict: criteriaEvaluation.verdict,
      history,
    };
  });
}

