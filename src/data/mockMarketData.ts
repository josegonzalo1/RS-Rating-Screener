// Generates 252 trading days of daily quotes for stock and benchmark SPY
function generateStockHistory(
  basePrice: number,
  annualGainPct: number,
  volatility: number,
  rsNewHighAhead: boolean,
  currentPriceTarget: number
): DailyQuote[] {
  const quotes: DailyQuote[] = [];
  const tradingDays = 252;
  const startDate = new Date();
  startDate.setDate(startDate.getDate() - 365);

  let currentPrice = basePrice;
  let currentSpy = 500;
  const spyTrend = 0.12 / tradingDays; // ~12% annual gain for SPY

  const prices: number[] = [];
  const spyPrices: number[] = [];

  const dailyStockDrift = Math.pow(1 + annualGainPct / 100, 1 / tradingDays) - 1;

  for (let i = 0; i < tradingDays; i++) {
    const d = new Date(startDate);
    d.setDate(d.getDate() + Math.floor((i * 365) / tradingDays));
    const dateStr = d.toISOString().split('T')[0];

    const spyNoise = Math.sin(i * 0.15) * 0.004 + (Math.random() - 0.49) * 0.008;
    currentSpy = currentSpy * (1 + spyTrend + spyNoise);

    let phaseBonus = 0;
    if (rsNewHighAhead && i > 180 && i < 220) {
      phaseBonus = 0.002;
    }
    const stockNoise = Math.sin(i * 0.22) * 0.012 + (Math.random() - 0.48) * volatility * 0.02;
    currentPrice = Math.max(5, currentPrice * (1 + dailyStockDrift + stockNoise + phaseBonus));

    const volume = Math.floor(1_500_000 + Math.random() * 3_000_000 * (1 + Math.abs(stockNoise) * 2));

    prices.push(currentPrice);
    spyPrices.push(currentSpy);

    quotes.push({
      date: dateStr,
      close: Number(currentPrice.toFixed(2)),
      open: Number((currentPrice * (1 + (Math.random() - 0.5) * 0.004)).toFixed(2)),
      high: Number((currentPrice * (1 + Math.random() * 0.012)).toFixed(2)),
      low: Number((currentPrice * (1 - Math.random() * 0.012)).toFixed(2)),
      volume,
      spyClose: Number(currentSpy.toFixed(2)),
      rsLine: Number(((currentPrice / currentSpy) * 100).toFixed(2)),
    });
  }

  // Adjust final price to target
  const factor = currentPriceTarget / (prices[prices.length - 1] || 1);
  for (let i = 0; i < tradingDays; i++) {
    const blend = i / tradingDays;
    const adj = 1 + (factor - 1) * blend;
    quotes[i].close = Number((quotes[i].close * adj).toFixed(2));
    quotes[i].high = Number(Math.max(quotes[i].close, quotes[i].high * adj).toFixed(2));
    quotes[i].low = Number(Math.min(quotes[i].close, quotes[i].low * adj).toFixed(2));
    quotes[i].rsLine = Number(((quotes[i].close / quotes[i].spyClose) * 100).toFixed(2));
  }

  // Compute Moving Averages
  for (let i = 0; i < tradingDays; i++) {
    if (i >= 49) {
      let sumP50 = 0;
      let sumR50 = 0;
      for (let j = i - 49; j <= i; j++) {
        sumP50 += quotes[j].close;
        sumR50 += quotes[j].rsLine;
      }
      quotes[i].sma50 = Number((sumP50 / 50).toFixed(2));
      quotes[i].rsSma50 = Number((sumR50 / 50).toFixed(2));
    }
    if (i >= 20) {
      let sumR21 = 0;
      for (let j = i - 20; j <= i; j++) {
        sumR21 += quotes[j].rsLine;
      }
      quotes[i].rsSma21 = Number((sumR21 / 21).toFixed(2));
    }
    if (i >= 199) {
      let sumP200 = 0;
      for (let j = i - 199; j <= i; j++) {
        sumP200 += quotes[j].close;
      }
      quotes[i].sma200 = Number((sumP200 / 200).toFixed(2));
    }
  }

  return quotes;
}

